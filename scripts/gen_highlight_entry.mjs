#!/usr/bin/env node
// Regenerates resources/highlight_entry.js from an installed highlight.js
// package. Every language module is imported but NOT registered at load time:
// registration (and grammar compilation) is deferred to the first fence that
// uses that language, so shipping all ~193 languages costs bundle size only.
// The upstream alias table is baked in at generation time, so no grammar has
// to be built just to resolve a fence tag.
//
// Usage:
//   npm install highlight.js@11.12.0 esbuild@0.28.2
//   node scripts/gen_highlight_entry.mjs node_modules/highlight.js
//   node_modules/.bin/esbuild resources/highlight_entry.js \
//     --bundle --format=iife --minify \
//     --alias:highlight.js=$PWD/node_modules/highlight.js \
//     --outfile=resources/highlight.min.js

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pkg = path.resolve(process.argv[2] ?? 'node_modules/highlight.js');
const langDir = path.join(pkg, 'lib', 'languages');
if (!fs.existsSync(langDir)) {
  console.error(`highlight.js languages not found: ${langDir}`);
  process.exit(1);
}

const names = fs
  .readdirSync(langDir)
  .filter((f) => f.endsWith('.js') && !f.endsWith('.js.js'))
  .map((f) => f.slice(0, -3))
  .sort();

const hljs = (await import(pathToFileURL(path.join(pkg, 'lib', 'core.js')))).default;

// Alias -> language name, as declared by the modules themselves. Building a
// definition here is cheap (grammar compilation happens at registration).
const aliasMap = {};
for (const name of names) {
  const def = (await import(pathToFileURL(path.join(langDir, `${name}.js`)))).default;
  let built;
  try {
    built = def(hljs);
  } catch {
    continue;
  }
  for (const alias of built.aliases ?? []) {
    aliasMap[alias.toLowerCase()] = name;
  }
}

// Fence tags that documents use but upstream does not alias the same way.
const overrides = {
  'batch': 'dos',
  'shell': 'bash',
  'toml': 'ini',
  'objective-c': 'objectivec',
  'pwsh': 'powershell',
  'golang': 'go',
  'c#': 'csharp',
  'vue': 'xml',
  'md': 'markdown',
  'proto': 'protobuf',
  'docker': 'dockerfile',
  'mk': 'makefile',
  'make': 'makefile',
  'patch': 'diff',
  'f90': 'fortran',
  'f95': 'fortran',
  'asm': 'x86asm',
  'nasm': 'x86asm',
  'sass': 'scss',
  'conf': 'nginx',
};
Object.assign(aliasMap, overrides);

const safe = (name) => 'lang_' + name.replace(/[^a-zA-Z0-9_]/g, '_');
const imports = names
  .map((n) => `import ${safe(n)} from 'highlight.js/lib/languages/${n}';`)
  .join('\n');
const defs = names.map((n) => `  '${n}': ${safe(n)},`).join('\n');
const aliases = Object.keys(aliasMap)
  .sort()
  .map((a) => `  ${JSON.stringify(a)}: '${aliasMap[a]}',`)
  .join('\n');

const template = `// Generated by scripts/gen_highlight_entry.mjs — do not edit by hand.
//
// highlight.js bundle entry. Every language module is imported, but
// registration is lazy: a language is registered (and its grammar compiled)
// the first time a fence asks for it. That keeps the payload at roughly 1 MB
// while making all ${names.length} languages available.
//
// Rendering pipeline: qjsc compiles this bundle to bytecode at build time
// (src/mdhtml/CMakeLists.txt and src/markdown_view/CMakeLists.txt); QuickJS
// evaluates it per worker and calls __highlight(code, language).
//
// To regenerate (pin the versions):
//   npm install highlight.js@11.12.0 esbuild@0.28.2
//   node scripts/gen_highlight_entry.mjs node_modules/highlight.js
//   node_modules/.bin/esbuild resources/highlight_entry.js \\
//     --bundle --format=iife --minify \\
//     --alias:highlight.js=$PWD/node_modules/highlight.js \\
//     --outfile=resources/highlight.min.js
//
// __highlight returns null for languages outside the registry, so the C++
// side falls back to plain escaping (no highlightAuto guessing: a wrong guess
// looks worse than no highlighting).

import hljs from 'highlight.js/lib/core';

${imports}

const DEFS = {
${defs}
};

// Fence tag or upstream alias -> registered language name.
const ALIAS = {
${aliases}
};

// hljs-xxx -> short CSS class names owned by resources/themes/*.css.
const CLASS_MAP = {
  keyword: 'kw',
  type: 'ty',
  literal: 'lit',
  built_in: 'bi',
  string: 'str',
  char: 'str',
  subst: 'str',
  regexp: 're',
  number: 'num',
  comment: 'cmt',
  doctag: 'cmt',
  title: 'tt',
  section: 'tt',
  function: 'fn',
  params: 'var',
  variable: 'var',
  attr: 'attr',
  attribute: 'attr',
  property: 'attr',
  meta: 'meta',
  tag: 'tag',
  name: 'tag',
  symbol: 'sym',
  'selector-tag': 'tag',
  'selector-class': 'sel',
  'selector-id': 'sel',
  'selector-attr': 'sel',
  'selector-pseudo': 'sel',
  operator: 'op',
  punctuation: 'op',
  keyframePosition: 'kw',
};

function fixClasses(html) {
  return html.replace(/class="([^"]*)"/g, (m, classes) => {
    const mapped = classes.split(/\\s+/).map((c) => {
      const name = c.startsWith('hljs-') ? c.slice(5) : c;
      return CLASS_MAP[name] || c;
    });
    return \`class="\${mapped.join(' ')}"\`;
  });
}

// The C++ side splits a fence into one <td> per line, so a span that crosses
// a newline must be closed at the break and reopened on the next line.
function splitSpansPerLine(html) {
  const open = [];
  let out = '';
  let i = 0;
  while (i < html.length) {
    if (html.startsWith('<span class="', i)) {
      const end = html.indexOf('>', i);
      const tag = html.slice(i, end + 1);
      const m = tag.match(/class="([^"]*)"/);
      open.push(m ? m[1] : '');
      out += tag;
      i = end + 1;
    } else if (html.startsWith('</span>', i)) {
      if (open.length) open.pop();
      out += '</span>';
      i += 7;
    } else if (html[i] === '\\n') {
      for (let k = 0; k < open.length; ++k) out += '</span>';
      out += '\\n';
      for (const cls of open) out += \`<span class="\${cls}">\`;
      i += 1;
    } else {
      out += html[i];
      i += 1;
    }
  }
  return out;
}

function resolveLanguage(lang) {
  const l = String(lang || '').toLowerCase();
  if (!l) return null;
  const name = DEFS[l] ? l : ALIAS[l];
  if (!name || !DEFS[name]) return null;
  if (!hljs.getLanguage(name)) {
    hljs.registerLanguage(name, DEFS[name]);
  }
  return name;
}

globalThis.__highlight = function (code, lang) {
  const language = resolveLanguage(lang);
  if (!language) return null;
  try {
    const out = hljs.highlight(code, {
      language,
      ignoreIllegals: true,
    }).value;
    return splitSpansPerLine(fixClasses(out));
  } catch (e) {
    return null;
  }
};
`;

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
fs.writeFileSync(
  path.join(repoRoot, 'resources', 'highlight_entry.js'), template);
console.log(
  `wrote resources/highlight_entry.js (${names.length} languages, ` +
  `${Object.keys(aliasMap).length} aliases)`);
